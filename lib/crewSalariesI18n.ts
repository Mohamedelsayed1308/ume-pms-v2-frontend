export type CrewKey = keyof typeof D;

export function crewText(locale: 'ar' | 'en', key: string, vars?: Record<string, string | number | null | undefined>): string {
  const pair = (D as Record<string, [string, string]>)[key];
  let s = pair ? pair[locale === 'en' ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v == null ? '—' : String(v));
  return s;
}

export function useCrewT() {
  const { locale } = useI18n();
  const lang: 'ar' | 'en' = locale === 'en' ? 'en' : 'ar';
  const t = useCallback((key: CrewKey, vars?: Record<string, string | number | null | undefined>) => crewText(lang, key, vars), [lang]);
  /** مفتاحٌ مركّب (kind.basic …) — يعود إلى المفتاح نفسه إن لم يُعرَّف. */
  const tk = useCallback((prefix: string, code: string, vars?: Record<string, string | number | null | undefined>) => crewText(lang, `${prefix}.${code}`, vars).replace(`${prefix}.`, ''), [lang]);
  return { t, tk, lang };
}
